/**
 * Writes overlay/tokens.gen.ts: the design system's custom properties the
 * overlay's stylesheet reads, in both themes, as one CSS string. The
 * overlay runs in a closed shadow root on pages dude does not own and loads
 * nothing, so it cannot link tokens.css; it carries this copy instead, made
 * from the same source tokens.css is (flattenTheme and the scales).
 *
 *   bun overlay/build-tokens.ts     (build.ts runs it before every build)
 *
 * Only the names in OVERLAY_TOKENS are emitted, under their DS names, so the
 * overlay's CSS reads `var(--ds-…)` as the app's CSS modules do. The
 * generated file is committed; test/tokens.test.ts fails when it is stale.
 */

import { join } from "node:path";
import {
  flattenTheme, focusRing, fontFamily, fontSize, fontWeight, lineHeight, radius, size, space, duration, easing,
  type ThemeMode,
} from "@dude/design-system/tokens";

/** The theme-dependent tokens the overlay uses, without the `--ds-` prefix. */
export const OVERLAY_THEME_TOKENS = [
  "color-canvas", "color-surface", "color-raised", "color-overlay", "color-sunken", "color-chrome", "color-field-bg",
  "color-border-subtle", "color-border", "color-border-strong",
  "color-text-strong", "color-text-primary", "color-text-secondary", "color-text-muted",
  "color-accent", "color-accent-hover", "color-accent-active", "color-accent-subtle", "color-accent-text", "color-on-accent",
  "color-focus-ring", "color-selection", "color-hover-wash", "color-active-wash", "color-scrim",
  "tone-neutral-fg", "tone-neutral-bg", "tone-neutral-solid", "tone-neutral-on-solid",
  "tone-info-solid", "tone-info-on-solid",
  "tone-success-fg", "tone-success-solid", "tone-success-on-solid",
  "tone-attention-fg", "tone-attention-solid",
  "tone-danger-fg",
  "shadow-1", "shadow-2", "shadow-3",
] as const;

/** The static scales the overlay uses: the same names and units tokens.css writes. */
export function overlayStaticTokens(): Record<string, string> {
  const px = (v: number) => `${v}px`;
  return {
    "font-sans": fontFamily.sans,
    "font-mono": fontFamily.mono,
    "text-2xs": px(fontSize["2xs"]), "text-xs": px(fontSize.xs), "text-sm": px(fontSize.sm), "text-md": px(fontSize.md),
    "leading-tight": String(lineHeight.tight), "leading-snug": String(lineHeight.snug), "leading-normal": String(lineHeight.normal),
    "weight-regular": String(fontWeight.regular), "weight-medium": String(fontWeight.medium), "weight-semibold": String(fontWeight.semibold),
    "space-2": px(space[2]), "space-4": px(space[4]), "space-6": px(space[6]), "space-8": px(space[8]),
    "space-12": px(space[12]), "space-16": px(space[16]), "space-20": px(space[20]),
    "radius-mark": px(radius.mark), "radius-control": px(radius.control), "radius-float": px(radius.float), "radius-full": px(radius.full),
    "size-control-sm": px(size.controlSm), "size-chip": px(size.chip), "size-badge-md": px(size.badgeMd),
    "duration-fast": `${duration.fast}ms`, "ease-standard": easing.standard,
    "focus-ring-width": px(focusRing.width), "focus-ring-offset": px(focusRing.offset),
  };
}

function decls(vars: Record<string, string>): string {
  return Object.entries(vars).map(([k, v]) => `--ds-${k}:${v}`).join(";");
}

function theme(mode: ThemeMode): Record<string, string> {
  const all = flattenTheme(mode);
  const out: Record<string, string> = {};
  for (const k of OVERLAY_THEME_TOKENS) {
    const v = all[k];
    if (v === undefined) throw new Error(`the design system has no --ds-${k}`);
    out[k] = v;
  }
  return out;
}

/** The CSS: scales on .root, dark as the default (dude's), light under data-theme=light. */
export function overlayTokensCss(): string {
  return [
    `.root{${decls(overlayStaticTokens())}}`,
    `.root,.root[data-theme=dark]{color-scheme:dark;${decls(theme("dark"))}}`,
    `.root[data-theme=light]{color-scheme:light;${decls(theme("light"))}}`,
  ].join("\n");
}

/** The text of tokens.gen.ts. */
export function overlayTokensModule(): string {
  return `// GENERATED by overlay/build-tokens.ts from @dude/design-system's tokens — do not edit by hand.\nexport const TOKENS_CSS = ${JSON.stringify(overlayTokensCss())};\n`;
}

export const TOKENS_MODULE = join(import.meta.dir, "tokens.gen.ts");

if (import.meta.main) {
  const text = overlayTokensModule();
  await Bun.write(TOKENS_MODULE, text);
  console.log(`wrote ${TOKENS_MODULE} (${text.length} bytes)`);
}

//go:generate go run ./cmd

// Package refusalgen renders Go format constants without importing their consumers.
package refusalgen

import (
	"bytes"
	"embed"
	"fmt"
	"go/format"
	"io/fs"
	"path"
	"regexp"
	"strings"
	"text/template"
)

//go:embed *.manifest
var manifests embed.FS

var outputs = []struct{ manifest, output, pkg string }{
	{"delivery.manifest", "internal/delivery/refusals.go", "delivery"},
	{"domain.manifest", "internal/delivery/refusals_domain.go", "delivery"},
	{"tools.manifest", "internal/agenttools/refusals.go", "agenttools"},
}

// The manifests preserve existing handle names and template keys; expressions
// describe their source, not executable Go or an argument-type registry.
var entry = regexp.MustCompile(`(?m)^\s*(\w+)\s*=.*?"(refusals/[^"]+)"`)

func Render(source fs.FS) (map[string][]byte, error) {
	set := template.New("").Option("missingkey=error").Funcs(template.FuncMap{
		"oneLine": func(s string) string { return strings.Join(strings.Fields(s), " ") },
		"clip": func(s string, n int) string {
			if len(s) > n {
				return s[:n]
			}
			return s
		},
		"join": strings.Join,
	})

	err := fs.WalkDir(source, "internal/delivery/agents/refusals", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || path.Ext(p) != ".md" {
			return err
		}
		b, err := fs.ReadFile(source, p)
		if err != nil {
			return err
		}
		_, err = set.New(strings.TrimSuffix(strings.TrimPrefix(p, "internal/delivery/agents/"), ".md")).Parse(strings.TrimSuffix(string(b), "\n"))
		return err
	})
	if err != nil {
		return nil, err
	}
	out := map[string][]byte{}
	for _, file := range outputs {
		manifest, err := manifests.ReadFile(file.manifest)
		if err != nil {
			return nil, err
		}
		var b bytes.Buffer
		fmt.Fprintf(&b, "// Code generated by refusalgen; DO NOT EDIT.\n\npackage %s\n\nconst (\n", file.pkg)
		for _, pair := range entry.FindAllStringSubmatch(string(manifest), -1) {
			t := set.Lookup(pair[2])
			if t == nil {
				return nil, fmt.Errorf("missing refusal %s", pair[2])
			}
			var text bytes.Buffer
			if err := t.Execute(&text, nil); err != nil {
				return nil, err
			}
			fmt.Fprintf(&b, "%s = %q\n", pair[1], text.String())
		}
		b.WriteString(")\n")
		out[file.output], err = format.Source(b.Bytes())
		if err != nil {
			return nil, err
		}
	}
	return out, nil
}

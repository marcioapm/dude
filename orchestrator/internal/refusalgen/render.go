//go:generate go run ./cmd

// Package refusalgen renders Go format constants without importing their consumers.
package refusalgen

import (
	"bytes"
	"embed"
	"fmt"
	"go/format"
	"io/fs"
	"path"
	"regexp"
	"sort"
	"strings"
	"text/template"
	"text/template/parse"
)

//go:embed *.manifest
var manifests embed.FS

var outputs = []struct{ manifest, output, pkg string }{
	{"delivery.manifest", "internal/delivery/refusals.go", "delivery"},
	{"domain.manifest", "internal/delivery/refusals_domain.go", "delivery"},
	{"tools.manifest", "internal/agenttools/refusals.go", "agenttools"},
}

// generated are the template prefixes every define under which needs a manifest entry.
var generated = []string{"refusals/tools/", "refusals/delivery/", "refusals/domain/"}

// The manifests preserve existing handle names and template keys; expressions
// describe their source, not executable Go or an argument-type registry.
var entry = regexp.MustCompile(`(?m)^\s*(\w+)\s*=.*?"(refusals/[^"]+)"`)

func Render(source fs.FS) (map[string][]byte, error) {
	set := template.New("").Option("missingkey=error")
	files := map[string]bool{}
	for _, prefix := range generated {
		err := fs.WalkDir(source, "internal/delivery/agents/"+strings.TrimSuffix(prefix, "/"), func(p string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() || path.Ext(p) != ".md" {
				return err
			}
			b, err := fs.ReadFile(source, p)
			if err != nil {
				return err
			}
			name := strings.TrimSuffix(strings.TrimPrefix(p, "internal/delivery/agents/"), ".md")
			files[name] = true
			_, err = set.New(name).Parse(strings.TrimSuffix(string(b), "\n"))
			return err
		})
		if err != nil {
			return nil, err
		}
	}
	// A refusal is a printf format rendered with nil: anything but one text
	// node would need data or functions the generator does not have.
	for _, t := range set.Templates() {
		if files[t.Name()] || t.Tree == nil {
			continue
		}
		if nodes := t.Tree.Root.Nodes; len(nodes) != 1 || nodes[0].Type() != parse.NodeText {
			return nil, fmt.Errorf("%s has a template action; a refusal is a printf format", t.Name())
		}
	}

	entries := map[string][][]string{}
	listed := map[string]bool{}
	for _, file := range outputs {
		manifest, err := manifests.ReadFile(file.manifest)
		if err != nil {
			return nil, err
		}
		entries[file.manifest] = entry.FindAllStringSubmatch(string(manifest), -1)
		for _, pair := range entries[file.manifest] {
			listed[pair[2]] = true
		}
	}
	var orphans []string
	for _, t := range set.Templates() {
		if !files[t.Name()] && !listed[t.Name()] && isGenerated(t.Name()) {
			orphans = append(orphans, t.Name())
		}
	}
	if len(orphans) > 0 {
		sort.Strings(orphans)
		return nil, fmt.Errorf("no manifest in internal/refusalgen lists %s", strings.Join(orphans, ", "))
	}

	out := map[string][]byte{}
	for _, file := range outputs {
		var b bytes.Buffer
		fmt.Fprintf(&b, "// Code generated by refusalgen; DO NOT EDIT.\n\npackage %s\n\nconst (\n", file.pkg)
		for _, pair := range entries[file.manifest] {
			t := set.Lookup(pair[2])
			if t == nil {
				return nil, fmt.Errorf("missing refusal %s", pair[2])
			}
			var text bytes.Buffer
			if err := t.Execute(&text, nil); err != nil {
				return nil, err
			}
			fmt.Fprintf(&b, "%s = %q\n", pair[1], text.String())
		}
		b.WriteString(")\n")
		src, err := format.Source(b.Bytes())
		if err != nil {
			return nil, err
		}
		out[file.output] = src
	}
	return out, nil
}

func isGenerated(name string) bool {
	for _, prefix := range generated {
		if strings.HasPrefix(name, prefix) {
			return true
		}
	}
	return false
}
